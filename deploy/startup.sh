#!/usr/bin/env bash
#
# Cloud bootstrap for the FHIR Directory Neo4j browser (NPDV-528).
#
# Runs once on first boot (as root) via AWS EC2 user-data or GCP startup-script.
# It installs Docker + Python, clones this repository, brings up Neo4j via the
# project installer (which generates a random password and applies the schema),
# and optionally downloads and imports a FHIR NDJSON dataset.
#
# Target OS: Ubuntu 22.04 LTS. All inputs are optional environment variables,
# normally prepended by deploy/aws/launch.sh or deploy/gcp/launch.sh:
#
#   FHIR_REPO_URL          git URL to clone   (default: public upstream)
#   FHIR_GIT_REF           branch/tag/sha     (default: main)
#   FHIR_INSTALL_DIR       install path       (default: /opt/fhir_directory_neo4j)
#   FHIR_DATA_URL          optional http(s) URL of a .tar.gz/.tgz/.zip of NDJSON
#                          files (or a directory of them) to import on boot
#   FHIR_NEO4J_HEAP_MAX    Neo4j heap max     (default: auto = 50% of RAM)
#   FHIR_NEO4J_PAGECACHE   Neo4j page cache   (default: auto = 30% of RAM)
#
# Progress is logged to /var/log/fhir-neo4j-deploy.log.

set -euo pipefail

REPO_URL="${FHIR_REPO_URL:-https://github.com/ftrotter-gov/fhir_directory_neo4j.git}"
GIT_REF="${FHIR_GIT_REF:-main}"
INSTALL_DIR="${FHIR_INSTALL_DIR:-/opt/fhir_directory_neo4j}"
DATA_URL="${FHIR_DATA_URL:-}"
HEAP_MAX="${FHIR_NEO4J_HEAP_MAX:-}"
PAGECACHE="${FHIR_NEO4J_PAGECACHE:-}"

LOG=/var/log/fhir-neo4j-deploy.log
exec > >(tee -a "$LOG") 2>&1
echo "=== fhir-neo4j deploy starting $(date -u +%Y-%m-%dT%H:%M:%SZ) ==="

# --- 1. OS packages -------------------------------------------------------
export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get install -y ca-certificates curl git python3 python3-venv python3-pip

# --- 2. Docker Engine + Compose plugin ------------------------------------
if ! command -v docker >/dev/null 2>&1; then
  echo "Installing Docker..."
  curl -fsSL https://get.docker.com | sh
fi
systemctl enable --now docker

# --- 3. Clone the repository ----------------------------------------------
if [ ! -d "$INSTALL_DIR/.git" ]; then
  echo "Cloning $REPO_URL ($GIT_REF) -> $INSTALL_DIR"
  git clone "$REPO_URL" "$INSTALL_DIR"
fi
cd "$INSTALL_DIR"
git fetch --all --tags --quiet || true
git checkout "$GIT_REF" --quiet || true
git pull --ff-only --quiet || true

# --- 4. Auto-size Neo4j memory from available RAM -------------------------
if [ -z "$HEAP_MAX" ] || [ -z "$PAGECACHE" ]; then
  mem_total_kb="$(awk '/MemTotal/ {print $2}' /proc/meminfo)"
  mem_total_mb=$(( mem_total_kb / 1024 ))
  [ -z "$HEAP_MAX" ]  && HEAP_MAX="$(( mem_total_mb / 2 ))m"       # 50% of RAM
  [ -z "$PAGECACHE" ] && PAGECACHE="$(( mem_total_mb * 3 / 10 ))m" # 30% of RAM
fi
echo "Neo4j memory: heap_max=$HEAP_MAX pagecache=$PAGECACHE"

# --- 5. Pre-create .env (random password + sizing) before the installer ---
if [ ! -f "$INSTALL_DIR/.env" ]; then
  PASSWORD="$(python3 -c 'import secrets,string; a=string.ascii_letters+string.digits; print("".join(secrets.choice(a) for _ in range(32)))')"
  umask 077
  cat > "$INSTALL_DIR/.env" <<ENV
# Generated by deploy/startup.sh. Do not commit this file.
NEO4J_AUTH=neo4j/${PASSWORD}
NEO4J_URI=bolt://localhost:7687
NEO4J_USER=neo4j
NEO4J_PASSWORD=${PASSWORD}
NEO4J_HEAP_MAX=${HEAP_MAX}
NEO4J_PAGECACHE=${PAGECACHE}
ENV
  echo "Wrote $INSTALL_DIR/.env with a generated Neo4j password."
fi

# --- 6. Bring up Neo4j (installer: venv, deps, compose up, schema) ---------
python3 download_install_neo4j_docker.py --timeout 300

# --- 7. Optional: download + import a dataset on first boot ----------------
if [ -n "$DATA_URL" ]; then
  echo "Downloading dataset from $DATA_URL"
  DATA_DIR="$INSTALL_DIR/data_downloads/incoming"
  mkdir -p "$DATA_DIR"
  tmp="$(mktemp)"
  curl -fsSL "$DATA_URL" -o "$tmp"
  case "$DATA_URL" in
    *.tar.gz|*.tgz) tar xzf "$tmp" -C "$DATA_DIR" ;;
    *.zip)          (cd "$DATA_DIR" && python3 -c "import zipfile,sys; zipfile.ZipFile(sys.argv[1]).extractall()" "$tmp") ;;
    *.ndjson|*.json) cp "$tmp" "$DATA_DIR/$(basename "$DATA_URL")" ;;
    *) echo "WARN: unrecognized dataset extension; leaving raw file in $DATA_DIR" ; cp "$tmp" "$DATA_DIR/data.bin" ;;
  esac
  rm -f "$tmp"
  # If the archive expanded into a single subdirectory, import that.
  import_target="$DATA_DIR"
  only_child="$(find "$DATA_DIR" -mindepth 1 -maxdepth 1 | head -2)"
  if [ "$(printf '%s\n' "$only_child" | wc -l)" -eq 1 ] && [ -d "$only_child" ]; then
    import_target="$only_child"
  fi
  echo "Importing from $import_target"
  ./.venv/bin/python scripts/import_or_update_ndjson.py "$import_target" --batch-size 5000 \
    --import-tag "boot_$(date -u +%Y%m%d)" || echo "WARN: import reported a non-zero status"
fi

touch "$INSTALL_DIR/.deploy_complete"
echo "=== fhir-neo4j deploy complete $(date -u +%Y-%m-%dT%H:%M:%SZ) ==="
echo "Neo4j Browser: http://<this-host>:7474  (user: neo4j; password in $INSTALL_DIR/.env)"
